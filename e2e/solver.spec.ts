import { expect, test } from "@playwright/test";

test("country solver combines feedback without looking up the daily answer", async ({ page, request }) => {
  const html = await (await request.get("/originle-solver")).text();
  expect(html).toContain('<link rel="canonical" href="https://originlegame.app/originle-solver"');
  expect(html).toContain("independent");
  expect(html).toContain("Natural Earth");
  expect(html).toContain('"@type":"WebApplication"');
  expect(html).not.toContain("The guest is Fixture");
  await page.goto("/originle-solver");
  await expect(page.getByRole("region", { name: "Candidate countries" })).toHaveCount(0);
  await page.getByLabel("Country you guessed (guess 1)", { exact: true }).selectOption("FR");
  await page.getByLabel("Distance shown (km), guess 1", { exact: true }).fill("0");
  await page.getByLabel("Continent clue (optional)", { exact: true }).selectOption("Europe");
  await page.getByRole("button", { name: "Find candidate countries", exact: true }).click();
  const results = page.getByRole("region", { name: "Candidate countries" });
  await expect(results.getByRole("heading", { name: /Belgium/ })).toBeVisible();
  await expect(results.getByRole("heading", { name: /France/ })).toHaveCount(0);
  await page.getByRole("button", { name: "Add another guess", exact: true }).click();
  await expect(results).toHaveCount(0);
  await page.getByLabel("Country you guessed (guess 2)", { exact: true }).selectOption("DE");
  await page.getByLabel("Distance shown (km), guess 2", { exact: true }).fill("0");
  await page.getByRole("button", { name: "Find candidate countries", exact: true }).click();
  await expect(results.getByRole("heading", { name: /Belgium/ })).toBeVisible();
  await expect(results.getByRole("heading", { name: /France|Germany/ })).toHaveCount(0);
  await page.getByLabel("Country you guessed (guess 2)", { exact: true }).selectOption("FR");
  await page.getByRole("button", { name: "Find candidate countries", exact: true }).click();
  await expect(page.getByRole("status")).toContainText(/duplicate|same country|once/i);
  await page.getByRole("button", { name: "Remove guess 2", exact: true }).click();
  await page.getByLabel("Distance shown (km), guess 1", { exact: true }).fill("20040");
  await page.getByLabel("Allow a distance difference of (km)", { exact: true }).fill("0");
  await page.getByRole("button", { name: "Find candidate countries", exact: true }).click();
  await expect(page.getByRole("status")).toContainText(/no .*match|no candidates/i);
  await page.getByRole("button", { name: "Clear guesses", exact: true }).click();
  await expect(page.getByLabel("Country you guessed (guess 1)", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Distance shown (km), guess 1", { exact: true })).toHaveValue("");
  await expect(results).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0);
});
